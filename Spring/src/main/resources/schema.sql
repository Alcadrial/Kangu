CREATE TABLE messages(
	sender VARCHAR(50) NOT NULL,
	receiver VARCHAR(50) NOT NULL,
	sender_enc_message VARCHAR(500) NOT NULL,
	receiver_enc_message VARCHAR(500) NOT NULL,
	message_mime_type VARCHAR(50) NOT NULL,
	send_timestamp TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
		--same send_datetime for multiple rows means that they are part of the same message possibly with a different mime type
	part_index NUMBER(2) DEFAULT 0 NOT NULL,
	PRIMARY KEY (sender, receiver, send_timestamp, part_index),
	CONSTRAINT "fKey_messages_sender_users_username"
		FOREIGN KEY (sender) REFERENCES users(username),
	CONSTRAINT "fKey_messages_receiver_users_username"
		FOREIGN KEY (receiver) REFERENCES users(username)
);

CREATE TABLE messages_read_cursors(
	sender VARCHAR(50) NOT NULL,
	receiver VARCHAR(50) NOT NULL,
	receive_timestamp TIMESTAMP WITH TIME ZONE DEFAULT '1-JAN-26 12.0.0 AM' NOT NULL,
	read_timestamp TIMESTAMP WITH TIME ZONE DEFAULT '1-JAN-26 12.0.0 AM' NOT NULL,
	is_blocked BOOLEAN DEFAULT false NOT NULL,
	PRIMARY KEY (sender, receiver),
	CONSTRAINT "fKey_messagesReadCursors_sender_users_username"
		FOREIGN KEY (sender) REFERENCES users(username),
	CONSTRAINT "fKey_messagesReadCursors_receiver_users_username"
		FOREIGN KEY (receiver) REFERENCES users(username)
);

CREATE INDEX messages_sender_receiver_index
	ON messages(sender, receiver);

