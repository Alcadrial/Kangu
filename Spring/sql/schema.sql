
ALTER SESSION SET CONTAINER = FREEPDB1;
ALTER SESSION SET CURRENT_SCHEMA = spring;

DROP DOMAIN IF EXISTS username_d FORCE;
DROP DOMAIN IF EXISTS accepted_mime_type_d FORCE;

DROP TABLE IF EXISTS users CASCADE CONSTRAINTS;
DROP TABLE IF EXISTS groups CASCADE CONSTRAINTS;
DROP TABLE IF EXISTS group_authorities CASCADE CONSTRAINTS;
DROP TABLE IF EXISTS group_members CASCADE CONSTRAINTS;
DROP TABLE IF EXISTS messages CASCADE CONSTRAINTS;
DROP TABLE IF EXISTS messages_read_cursors CASCADE CONSTRAINTS;

CREATE DOMAIN username_d AS VARCHAR(50) STRICT
	NOT NULL
	CONSTRAINT "UsernameDomain_validChars"
		CHECK (REGEXP_INSTR(username_d, '^[a-zA-Z0-9_-]+$'));

CREATE DOMAIN accepted_mime_type_d AS ENUM (
	TEXT = 'text/plain'--,
--	MARKDOWN = 'text/markdown',
--	PNG = 'image/png',
--	JPEG = 'image/jpeg',
--	GIF = 'image/gif'
);


CREATE TABLE users(
	username VARCHAR(50) NOT NULL,
	password NCHAR(60) NOT NULL,
	enabled BOOLEAN NOT NULL,
	email VARCHAR(100) NOT NULL,
	PRIMARY KEY (username),
	DOMAIN username_d (username),
	DOMAIN email_d (email)
);

CREATE TABLE groups(
	id NUMBER(9) GENERATED BY DEFAULT AS IDENTITY (START WITH 1), 
	group_name VARCHAR(50) NOT NULL,
	PRIMARY KEY (id)
);

CREATE TABLE group_authorities(
	group_id NUMBER(9) NOT NULL,
	authority VARCHAR(50) NOT NULL,
	CONSTRAINT "fKey_groupAuthorities_groupId_groups_id"
		FOREIGN KEY (group_id) REFERENCES groups(id)
);

CREATE TABLE group_members(
	group_id NUMBER(9) NOT NULL,
	username VARCHAR(50) NOT NULL,
	CONSTRAINT "fKey_groupMembers_groupId_groups_id"
		FOREIGN KEY (group_id) REFERENCES groups(id)
);

