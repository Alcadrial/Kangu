
ALTER SESSION SET CONTAINER = FREEPDB1;


CREATE TABLESPACE spring DATAFILE 'spring' SIZE 100M;

CREATE USER spring
    IDENTIFIED BY ${SPRING_PASSWORD}
	DEFAULT TABLESPACE spring
	QUOTA UNLIMITED ON spring;
GRANT CREATE SESSION TO spring;


CREATE TABLESPACE keycloak DATAFILE 'keycloak' SIZE 100M REUSE;

CREATE USER keycloak
    IDENTIFIED BY ${KEYCLOAK_PASSWORD}
	DEFAULT TABLESPACE keycloak
	QUOTA UNLIMITED ON keycloak;
GRANT CREATE SESSION TO keycloak;